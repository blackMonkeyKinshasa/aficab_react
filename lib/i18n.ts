export type TranslationKey = keyof typeof translations.fr;

export function translate(language: AppLanguage, key: TranslationKey) {
  return translations[language][key] ?? translations.fr[key];
}

export function formatTranslation(
  template: string,
  values: Record<string, string | number | undefined>
) {
  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value ?? '')),
    template
  );
}

export function getAppLocale(language: AppLanguage) {
  return language === 'fr' ? 'fr-FR' : 'en-US';
}

export function getPaperDateLocale(language: AppLanguage) {
  return language;
}

export function getPlacesLanguage(language: AppLanguage) {
  return language;
}

type AppLanguageStoreState = {
  language: AppLanguage;
};

export function useI18n() {
  const language = useAppLanguageState((state: AppLanguageStoreState) => state.language);

  return {
    language,
    t: (key: TranslationKey) => translate(language, key),
    tf: (key: TranslationKey, values: Record<string, string | number | undefined>) =>
      formatTranslation(translate(language, key), values),
    appLocale: getAppLocale(language),
    paperDateLocale: getPaperDateLocale(language),
    placesLanguage: getPlacesLanguage(language),
  };
}
